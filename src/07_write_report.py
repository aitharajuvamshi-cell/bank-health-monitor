def p(v, d=1):
    return "n/a" if v is None else f"{v:,.{d}f}%"


def n(v, d=0):
    return "n/a" if v is None else f"{v:,.{d}f}"


def ordn(v):
    v = int(round(v))
    suf = "th" if 10 <= v % 100 <= 20 else {1: "st", 2: "nd", 3: "rd"}.get(v % 10, "th")
    return f"{v}{suf}"


def s(v, d=1):
    return "n/a" if v is None else f"{v:+,.{d}f}%"


svb, sig, frc, wal = Q7["cases"]
rule, logit, gbm = MR
issuers = q2["issuers"]
cap = q4["growth_during_cap_pct"]

score_rows = "\n".join(
    f"| {r['name']} | {n(r['assets_bn'])} | {n(r['ROA'], 2)} | {n(r['NIMY'], 2)} | {n(r['EEFFR'], 1)} | "
    f"{n(r['NTLNLSR'], 2)} | {n(r['NCLNLSR'], 2)} | {n(r['RBC1AAJ'], 2)} | {n(r['uninsured_share'], 1)} | {n(r['unreal_loss_to_t1'], 1)} |"
    for r in q3["rows"])
med = q3["median_100bn_plus"]
issuer_rows = "\n".join(f"| {r['name']} | {n(r['card_bal_bn'])} | {p(r['nco_rate_t4'], 2)} | {p(r['dq30_latest'], 2)} | {p(r['card_share_of_loans'], 0)} |" for r in issuers)
model_rows = "\n".join(f"| {r['screen']} | {n(r['auc'], 3)} | {p(r['capture_top1'])} | {p(r['capture_top2'])} | {p(r['capture_top5'])} | {p(r['precision_top2'])} |" for r in MR)
prof_rows = "\n".join(f"| {r['label']} | {n(r['failed_median'], 2)} | {n(r['survivor_median'], 2)} |" for r in q5["profile"])
