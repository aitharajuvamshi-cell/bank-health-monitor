case_rows = "\n".join(f"| {c['name']} | {n(c['assets_bn'])} | {c['red_flags']} | {ordn(c['credit_score_pct'])} | {n(c['ROA'], 2)} | {n(c['noncurrent'], 2)} | {n(c['uninsured_share'], 1)} | {n(c['unreal_loss_to_t1'], 1)} |" for c in Q7["cases"])
